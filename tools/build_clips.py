#!/usr/bin/env python3
"""Build resources/clips.md (lesson -> video clips) from the concept indexes.

Usage:
    python3 tools/build_clips.py [--videos resources/videos] [--out resources/clips.md]
                                 [--syllabus syllabus.md] [--player URL]

Reads the "## Concept index" table in each resources/videos/NN.md
(| Start | End | Lesson | Concept |, times as m:ss or h:mm:ss) and writes, for
every syllabus lesson, the clips that cover it, as links to the clip player
that plays just that segment. Standard library only. Re-run after any edit.
"""
import argparse
import glob
import os
import re
from urllib.parse import quote

PLAYER = "https://dylanlmartin.github.io/video_embedding/"


def secs(t):
    t = re.sub(r"[\[\]]|\(.*?\)", "", t).strip()  # tolerate [m:ss](link) cells
    if not re.fullmatch(r"\d+(:\d{1,2}){0,2}", t):
        return None
    n = 0
    for p in t.split(":"):
        n = n * 60 + int(p)
    return n


def fmt(sec):
    h, m, s = sec // 3600, sec % 3600 // 60, sec % 60
    return f"{h}:{m:02d}:{s:02d}" if h else f"{m:02d}:{s:02d}"


def rows(text, heading):
    m = re.search(rf"^## {heading}\s*$(.*?)(?=^## |\Z)", text, re.M | re.S)
    if not m:
        return []
    out = []
    for line in m.group(1).splitlines():
        cells = [c.strip() for c in line.strip().strip("|").split("|")]
        if line.strip().startswith("|") and len(cells) >= 4 and not set(cells[0]) <= set("-: "):
            out.append(cells)
    return out


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--videos", default="resources/videos")
    ap.add_argument("--out", default="resources/clips.md")
    ap.add_argument("--syllabus", default="syllabus.md")
    ap.add_argument("--player", default=PLAYER)
    a = ap.parse_args()

    titles = {}
    if os.path.exists(a.syllabus):
        for line in open(a.syllabus, encoding="utf-8"):
            m = re.match(r"\|\s*(\d+)\s*\|\s*(.+?)\s*\|\s*$", line)
            if m:
                titles[m.group(1).zfill(2)] = m.group(2)

    clips, problems = {}, []
    for path in sorted(glob.glob(os.path.join(a.videos, "*.md"))):
        text = open(path, encoding="utf-8").read()
        num = os.path.basename(path)[:-3]
        head = re.search(r"^# (.+)$", text, re.M)
        vid = re.search(r"youtu\.be/([A-Za-z0-9_-]{11})|[?&]v=([A-Za-z0-9_-]{11})", text)
        if not vid:
            problems.append(f"{path}: no video id")
            continue
        vid = vid.group(1) or vid.group(2)
        label = re.sub(r"^\d+:\s*", "", head.group(1)) if head else num
        for cells in rows(text, "Concept index"):
            if cells[0].lower() == "start":
                continue
            start, end, lessons, concept = secs(cells[0]), secs(cells[1]), cells[2], cells[3]
            if start is None or end is None or end <= start:
                problems.append(f"{path}: bad times in row {cells}")
                continue
            for les in re.findall(r"\d+", lessons):
                clips.setdefault(les.zfill(2), []).append((num, start, end, vid, label, concept))

    lines = ["# Lesson → video clips", "",
             "Generated by `tools/build_clips.py` from the concept indexes in",
             "`resources/videos/NN.md`. Do not edit by hand; edit the indexes and re-run.",
             "Each link plays only that segment and stops by itself.", ""]
    order = sorted(set(titles) | set(clips), key=int)
    uncovered = []
    for les in order:
        lines.append(f"## {les} · {titles.get(les, '')}".rstrip(" ·"))
        lines.append("")
        if les not in clips:
            lines += ["_No video coverage: teach from the text or first principles._", ""]
            uncovered.append(les)
            continue
        for num, s, e, vid, label, concept in sorted(clips[les]):
            t = quote(f"{label}: {concept}", safe="")
            url = f"{a.player}?v={vid}&start={s}&end={e}&title={t}"
            lines.append(f"- V{num} [{fmt(s)}–{fmt(e)}]({url}): {concept}")
        lines.append("")
    if uncovered:
        lines += ["## Lessons without video coverage", "", ", ".join(uncovered), ""]
    os.makedirs(os.path.dirname(a.out) or ".", exist_ok=True)
    open(a.out, "w", encoding="utf-8").write("\n".join(lines))
    n = sum(len(v) for v in clips.values())
    print(f"wrote {a.out}: {n} clips across {len(clips)} lessons; {len(uncovered)} lessons uncovered")
    for p in problems:
        print("warning:", p)


if __name__ == "__main__":
    main()
